class ImageDataset(Dataset):
    def __init__(self, root_A,root_B, transforms_=None, unaligned=False, mode='train',compactSeg=False, size=240):
        self.transform = transforms.Compose(transforms_)
        self.unaligned = unaligned
        self.files_A = sorted(glob.glob(os.path.join(root_A) + '/*.*'))
        if root_B is None:
            root_B = root_A.replace('A','B').replace('ct','m$r$i$').replace('mri','ct').replace('m$r$i$','mri')
            print('Autogenerated root_B:',root_B)
        self.files_B = sorted(glob.glob(os.path.join(root_B) + '/*.*'))
        
        assert (len(self.files_A)>0), f'No file found in {root_A}'
        assert (len(self.files_B)>0), f'No file found in {root_B}'
        self.compactSeg = compactSeg
        self.size = size
    def load_file(self, name):
        if name.endswith('.npz'):
            f = np.load(name)
            arr = f['l'].astype('f')
            if 's' in f:
                seg = f['s'].astype('f')
                if self.compactSeg:
                    seg = np.logical_xor.reduce(seg,axis=0)
            else:
                seg = None
            f.close()
            arr = (2*(arr)/(3000.)-1)
            n = torch.tensor(arr)
            #padding/squaring
            n,seg = padding(n,seg,self.size)
            return [n,seg]
        return self.transform(Image.open(name))

    def __getitem__(self, index):
        item_A,seg_A = self.load_file(self.files_A[index % len(self.files_A)])
        #print(Image.open(self.files_A[index % len(self.files_A)]).getpixel((100,100)))
        if self.unaligned:
            item_B,seg_B = self.load_file(self.files_B[random.randint(0, len(self.files_B) - 1)])
        else:
            item_B,seg_B = self.load_file(self.files_B[index % len(self.files_B)])

        return item_A, item_B, seg_A, seg_B

    def __len__(self):
        #return max(len(self.files_A), len(self.files_B))
        return len(self.files_A)


