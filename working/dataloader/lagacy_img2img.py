def discover(start,filenames,files=[],):
    flair=filenames['f2']
    skull=filenames['skull']
    
    
    targetFile = os.path.join(start,flair)
    if skull is not None:
        skullFile = os.path.join(start,skull)
    #check if valid
    #print(start,len(files),os.path.isfile(targetFile),os.path.isfile(skull))
    #print('flair\t',targetFile,'\nskull\t',skull)
    if (skull is None or len(glob.glob(skullFile))!=0) and len(glob.glob(targetFile))!=0:
        files.append(start)
        #print(start,len(files))
    #calling subdirectors
    if os.path.isdir(start):
        dirs = os.listdir(str(start))
        for f in dirs:
            f = os.path.join(start,f)
            if os.path.isdir(f):
                discover(f,filenames,files)
    return files

def padding(n,seg,size):
    if n.shape[0] != size or n.shape[1] != size:
        (a,b)=n.shape
        deltah = 0.5*(size-a)
        deltaw = 0.5*(size-b)
        padding=((ceil(deltah),floor(deltah)),(ceil(deltaw),floor(deltaw)))
        n=np.pad(n,padding,mode='constant',constant_values=-1)
        #print(padding)
        if not seg is None:
            (_,a,b)=seg.shape
            deltah = 0.5*(size-a)
            deltaw = 0.5*(size-b)
            padding=((0,0),(ceil(deltah),floor(deltah)),(ceil(deltaw),floor(deltaw)))
            seg=np.pad(seg,padding,mode='constant',constant_values=0)
    return (n,seg)

class NIIDataset():
    def __init__(self, root,store = 3, size = 240,filenames=None):
        if isinstance(root, str):
            root = discover(root,filenames)
        self.files_A = root #sorted(glob.glob(os.path.join(root, '%s/NII' % mode) + '/*.*'))
        self.store = store
        self.size = size
        self.filenames = filenames
    
    def load_file(self, loc):
        factor = 1
        if self.filenames is None:
            flair='f2.aligned.nii.gz'
            skull='skullmap.nii.gz'
        else:
            flair=self.filenames['f2']
            skull=self.filenames['skull']
            if 'factor' in self.filenames:
                factor = self.filenames['factor']
        nii_in = glob.glob(os.path.join(loc,flair))[-1]
        if not skull is None:
            skull_in = glob.glob(os.path.join(loc,skull))[-1]
            nii_out = os.path.join(loc,'f2.aligned.stripped.nii.gz')
            data = stripSkull(nii_in,skull_in,nii_out,store=True)
        else:
            nii_data = nib.load(str(nii_in))
            affine = nii_data.affine
            data = nii_data.get_data()*factor
        if data.max() < 500:
            data*=10
        data = data.astype(float)
        return NII_SUB_Dataset(data,loc,self.size,self.store,affine)

    def getenum(self):
        for index in range(len(self)):
            yield (index, self.load_file(self.files_A[index % len(self.files_A)]))
    def __len__(self):
        return len(self.files_A)
   


class NII_SUB_Dataset(Dataset):
    def __init__(self, npa, loc,size,num_store, affine ):
        self.files_A = [i for _,i,_ in cropLayers(npa,loc=loc,size=size,translate=(0,0))]
        self.num_store = num_store
        self.imges=[]
        self.loc = loc
        self.size=size
        self.affine = affine
        #self.orginal_size = min(orginal_size,size) #reducing size is not supported jet.
        for _ in range(num_store):
            self.imges.append(np.zeros((len(self.files_A),size,size),npa.dtype))

    def load_file(self, idx):
        #print(idx,type(idx))
        arr = self.files_A[idx]
        arr = (2*(arr)/(3000.)-1)
        n = torch.tensor(arr)
        return n
        
    def __getitem__(self, index):
        item_A = self.load_file(index)
        return item_A

    def __len__(self):
        return len(self.files_A)
    def setlayer(self, layer_list,idx):
        for i in range(self.num_store):
            self.imges[i][idx] = squarify2D(np.squeeze(layer_list[i]).t().cpu(),val=self.size)
    def store(self, f_list):
        for i in range(self.num_store):
            #print(self.imges[i].sum(),self.imges[i].max(),self.imges[i].min())
            if self.affine is None:
                self.affine = np.eye(4)
            img = nib.Nifti1Image(self.imges[i].T, self.affine)
            nib.save(img,f_list[i])
    def getNii(self):
        return [self.imges[i].T for i in range(self.num_store)]
